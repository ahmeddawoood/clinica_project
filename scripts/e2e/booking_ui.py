"""Booking UI states and real submission, using synthetic localhost fixtures."""
import datetime, pathlib, re
from playwright.sync_api import sync_playwright, expect
out=pathlib.Path('e2e-results');out.mkdir(exist_ok=True)
with sync_playwright() as pw:
    browser=pw.chromium.launch()
    context=browser.new_context(viewport={'width':1440,'height':1050})
    page=context.new_page()
    page.goto('http://127.0.0.1:8082/login')
    page.locator('[name=username]').fill('mihai@email.com')
    page.locator('[name=password]').fill('patient123')
    page.locator('button[type=submit]').click()
    page.wait_for_url('**/patient/dashboard')
    page.goto('http://127.0.0.1:8082/patient/book')
    expect(page.locator('#bookingSubmit')).to_be_disabled()
    day=datetime.date.today()+datetime.timedelta(days=120)
    while day.weekday()>4: day+=datetime.timedelta(days=1)
    page.locator('#doctorSelect').select_option(index=1)
    # Failure must not leave a stale, submittable selection.
    page.route('**/api/slots/**',lambda route:route.fulfill(status=503,body='unavailable'))
    page.locator('#bookingDate').fill(str(day))
    expect(page.locator('#retrySlots')).to_be_visible()
    expect(page.locator('#bookingSubmit')).to_be_disabled()
    page.unroute('**/api/slots/**')
    page.locator('#retrySlots').click()
    expect(page.locator('[name=selectedSlot]').first).to_be_visible()
    page.locator('[name=selectedSlot]').first.check()
    expect(page.locator('#bookingSubmit')).to_be_enabled()
    assert page.locator('#appointmentDate').input_value().startswith(str(day)+'T')
    page.screenshot(path=str(out/'booking-desktop.png'),full_page=True)
    page.set_viewport_size({'width':390,'height':844})
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth + 1')
    page.screenshot(path=str(out/'booking-mobile.png'),full_page=True)
    page.locator('#notes').fill('Synthetic browser booking')
    page.locator('#bookingSubmit').click()
    page.wait_for_url(re.compile(r'.*/patient/appointments/\d+/pay'))
    print('PASS booking UI: retry, slot selection, summary, mobile overflow and payment redirect')
    browser.close()
